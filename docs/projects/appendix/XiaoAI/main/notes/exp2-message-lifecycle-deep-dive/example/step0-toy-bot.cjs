// ============================================================
// 第 0 步：最裸版本（toy bot）
// ============================================================
//
// 【本文件没有任何"站"】—— 这就是一切开始的地方。
//
// 功能：收到一条消息 → 调一次模型 → 回复。
//
// 用法：
//   node step0-toy-bot.js
//
// 它暴露的问题（后面 6 步每一步修一个）：
//   问题1：模型挂了 → 进程直接崩（第1步修）
//   问题2：用户连发 → 并发乱序、写坏会话（第2步修）
//   问题3：没有记忆，每条消息都是陌生人（第3步修）
//   问题4：没有持久化，重启全忘（第4步修）
//   问题5：模型不能执行命令（第5步修）
//   问题6：没有校验防护（第6步修）
//
// 教学约定（全部 7 个文件通用）：
//   - "模型"是 mock 的：echo 模型，原样返回消息（带固定前缀）
//   - 每步只标 【增量】 的代码是新加的，其余从上一步原样复制
//   - 每步文件末尾有"运行观察点"：跑起来该看到什么
// ============================================================

const { EventEmitter } = require("events");

// ---------- mock 模型（后续所有步骤共用这个设计） ----------
// 真实世界里这里是 anthropic.messages.create()。
// 我们 mock 成"回声模型"：把收到的消息包一层返回。
// 这样整个系列不依赖任何 API key，随时能跑。
const mockModel = {
  async create({ messages }) {
    const last = messages[messages.length - 1];
    return {
      content: [{ type: "text", text: `[model] 你说的是: ${last.content}` }],
      usage: { input_tokens: 10, output_tokens: 10 },
    };
  },
};

// ---------- "网关"：一个极简的消息入口 ----------
// 真实网关是 WS 服务器（见实验1补课的握手流程），这里简化成 EventEmitter。
const gateway = new EventEmitter();

// ---------- 核心逻辑：全部逻辑挤在一个函数里 ----------
gateway.on("message", async (text) => {
  // 没有路由：不知道这是谁的会话
  // 没有队列：来一条处理一条，来三条并发处理三条
  // 没有持久化：上一条聊了什么，这里完全不知道
  const reply = await mockModel.create({
    messages: [{ role: "user", content: text }], // ← 每次都是空的上下文！
  });
  console.log(`↩ 回复: ${reply.content[0].text}`);
});

// ---------- 模拟用户 ----------
(async () => {
  console.log("=== 第 0 步：最裸版本 ===");
  gateway.emit("message", "你好");
  gateway.emit("message", "今天天气如何");
})();

